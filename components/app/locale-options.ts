/** Adds `current` to the options when a stored value is not in the curated list. */
export function withCurrent(options: SelectOption[], current: string | null | undefined) {
  if (!current || options.some((o) => o.value === current)) return options;
  return [{ value: current, label: current }, ...options];
}
